/**
 * Album and collection icons.
 *
 * Any Material Design Icons name (`mdiCameraOutline`, ...) is a valid icon. The
 * server owns the catalogue as data (`mdi-icon-names.json`, generated from
 * `@mdi/js` {@link MDI_ICON_CATALOGUE_VERSION}) so it can validate writes and
 * serve the names plus the categorised suggested set to every client; clients
 * never bundle the catalogue to know what is valid.
 *
 * Icons from the extra packs (Tabler Icons, Material Symbols and a hand-picked
 * part of IconOven) are valid too, stored as the Iconify id `<prefix>:<name>`
 * (`tabler:rollercoaster`). `icon-pack-names.json` lists them; it is written by
 * `node web/scripts/icon-packs.mjs` from the packs the web build draws, and a
 * web unit test fails when the two drift apart.
 *
 * The 31 kebab-case keys in {@link LEGACY_ALBUM_ICON_KEYS} were the only values
 * accepted before the catalogue existed and are still stored on older albums.
 * They stay valid on read and write so existing data is never rejected.
 *
 * The suggested groups started as `collectionIconGroups` in the approved design
 * template (design/frameleaf/template/src/collections-data.mjs) and have since
 * grown here (family, life events, concerts and shows, theme parks, more trips
 * and holidays). Every name in them is a valid icon and appears once; a unit
 * test enforces that.
 */
