test('a case is outside normal form exactly when it is marked so', () => {
  for (const entry of fixtures.cases) {
    if (!applied(entry)) {
      assert.notEqual(entry.outsideNormalForm, true, `${entry.id} is rejected, so it cannot be outside normal form`);
      continue;
    }
    assert.equal(entry.expect.fixedPoint, entry.outsideNormalForm !== true, `${entry.id}: fixedPoint and outsideNormalForm disagree`);
  }
  // Section 11 lists exactly these edits as ones a native client refuses.
  assert.deepEqual([...outside].sort(), [
    'clip.move/overlap-is-not-checked',
    'clip.setSpeed/above-ten',
    'clip.setTransform/rotation-is-not-reduced',
    'clip.update/volume-is-not-clamped',
  ]);
  // Each of them breaks the schema or the no-overlap rule, which is why a native client refuses it.
  for (const entry of fixtures.cases.filter((candidate) => outside.has(candidate.id))) {
    const broken = validate(schema, entry.expect.graph).length > 0 || overlapsOf(entry.expect.graph).length > 0;
    assert.ok(broken, `${entry.id} is marked outside normal form but breaks no rule`);
  }
});

