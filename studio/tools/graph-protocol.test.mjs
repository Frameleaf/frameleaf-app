/**
 * Section 8.3 of the page: one table row per graph-changing command, as
 * `| \`command\` | Status | Section | Native rule |`.
 */
function protocolRows() {
  const start = page.indexOf('\n### 8.3 ');
  const end = page.indexOf('\n## 9. ', start);
  assert.ok(start >= 0 && end > start, 'the page has no section 8.3');
  const rows = [];
  for (const line of page.slice(start, end).split('\n')) {
    const cells = line.split('|').map((cell) => cell.trim());
    const id = /^`([A-Za-z.]+)`$/.exec(cells[1] ?? '')?.[1];
    if (id) rows.push({ id, status: cells[2], section: cells[3], rule: cells[4] });
  }
  return rows;
}
/** The text of the heading numbered `section`, or undefined: `### 12.3 …`, `#### 12.3.1 …`, `## 9. …`. */
const headingOf = (section) =>
  page
    .split('\n')
    .map((line) => /^#{2,4} (\d+(?:\.\d+)*)\.? (.*)$/.exec(line))
    .find((match) => match?.[1] === section)?.[2];

