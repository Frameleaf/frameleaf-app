test('14.2.3: a case settles on load exactly when it is marked so, and its settled digest follows from the rule', () => {
  let settling = 0;
  for (const entry of fixtures.cases.filter(applied)) {
    const { graph, settled } = entry.expect;
    if (entry.settlesOnLoad !== true) {
      assert.equal(settled, undefined, `${entry.id} records a settled graph but is not marked`);
      // Outside normal form is a different thing: loading changes what a person made.
      if (!outside.has(entry.id)) assert.equal(graphDigest(settle(graph)), entry.expect.digest, `${entry.id} is not settled but is not marked`);
      continue;
    }
    assert.notEqual(entry.outsideNormalForm, true, `${entry.id} cannot be both`);
    assert.equal(settled.fixedPoint, true, `${entry.id} does not settle in one load`);
    assert.notEqual(settled.digest, entry.expect.digest, `${entry.id} is marked but was already settled`);
    // The engine's loaded graph is the recorded graph with the two changes of 14.2.3, and nothing else.
    assert.equal(graphDigest(settle(graph)), settled.digest, `${entry.id}: settled digest`);
    assert.equal(envelopeDigest(settle(graph), build.upstreamCommit), settled.envelopeDigest, `${entry.id}: settled envelope digest`);
    settling++;
  }
  for (const entry of fixtures.cases.filter((candidate) => !applied(candidate))) {
    assert.notEqual(entry.settlesOnLoad, true, `${entry.id} is rejected, so it cannot settle`);
  }
  assert.ok(settling >= 20, `only ${settling} cases settle on load`);
});

