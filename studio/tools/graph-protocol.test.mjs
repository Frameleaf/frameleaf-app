/* Part 2 (FL-307): section 12 */

const part2 = Object.entries(fixtures.commandStatus)
  .filter(([, entry]) => entry.story === 'FL-307')
  .map(([id]) => id)
  .sort();
const part2Cases = fixtures.cases.filter((entry) => entry.story === 'FL-307');
/** Cases whose batch is one envelope of `command`, so the base graph is the graph the command saw. */
const single = (command) => part2Cases.filter((entry) => entry.envelopes.length === 1 && entry.envelopes[0].id === command);
const lastFrameOf = (graph) => Math.max(0, ...(graph.timeline.items ?? []).map((item) => item.from + item.durationInFrames));
const itemOf = (graph, id) => graph.timeline.items.find((item) => item.id === id);

test('part 2 covers its 28 commands with applied and rejected cases', () => {
  assert.equal(part2.length, 28);
  for (const command of part2) {
    const cases = part2Cases.filter((entry) => entry.id.startsWith(`${command}/`));
    for (const entry of cases) assert.ok(entry.covers.includes(command), `${entry.id} does not cover ${command}`);
    const count = (status) => cases.filter((entry) => entry.expect.status === status).length;
    assert.ok(count('rejected') > 0, `${command} has no rejected case`);
    // 12.8.4: music.add is always refused at this revision.
    if (command === 'music.add') assert.equal(count('applied'), 0, 'music.add must never apply');
    else assert.ok(count('applied') > 0, `${command} has no applied case`);
  }
});

test('every refusal names an envelope of its batch and one of the three reasons', () => {
  for (const entry of fixtures.cases.filter((candidate) => candidate.expect?.status === 'rejected')) {
    assert.ok(['invalid', 'failed', 'not-implemented'].includes(entry.expect.reason), `${entry.id}: ${entry.expect.reason}`);
    assert.ok(Number.isInteger(entry.expect.index) && entry.expect.index >= 0, entry.id);
    assert.ok(entry.expect.index < entry.envelopes.length, `${entry.id}: index outside the batch`);
    assert.equal(typeof entry.expect.detail, 'string', entry.id);
  }
});

test('the graph-wide rules of part 2 hold for every graph in normal form', () => {
  for (const [name, graph] of normalGraphs()) {
    const { timeline, metadata } = graph;
    if (!timeline) continue;
    // Section 5: no two clips of a track share a frame unless a transition joins them.
    assert.deepEqual(overlapsOf(graph), [], `${name}: overlap`);
    // 12.2.8: tracks are stored in ascending order and classic names follow position.
    const orders = timeline.tracks.map((track) => track.order);
    assert.deepEqual(orders, orders.toSorted((a, b) => a - b), `${name}: tracks are not in ascending order`);
    for (const [id, expected] of classicNames(timeline.tracks)) {
      assert.equal(timeline.tracks.find((track) => track.id === id).name, expected, `${name}: track ${id}`);
    }
    // Every clip is on a track of the graph, and clip ids are unique.
    const tracks = new Set(timeline.tracks.map((track) => track.id));
    const ids = timeline.items.map((item) => item.id);
    assert.equal(new Set(ids).size, ids.length, `${name}: duplicate clip id`);
    for (const item of timeline.items) assert.ok(tracks.has(item.trackId), `${name}: ${item.id} is on no track`);
    // 12.2.4: a media clip's source window is not empty and lies inside its source.
    for (const item of timeline.items.filter((candidate) => ['video', 'audio'].includes(candidate.type))) {
      assert.ok(item.sourceStart < item.sourceEnd, `${name}: ${item.id} has an empty source window`);
      if (item.sourceDuration !== undefined) assert.ok(item.sourceEnd <= item.sourceDuration, `${name}: ${item.id} runs past its source`);
    }
    // 12.2.6, rules 1 to 4: every transition left in a graph is one that repair keeps.
    for (const transition of timeline.transitions ?? []) {
      assert.ok(transitionKept(transition, graph), `${name}: transition ${transition.id} should have been removed`);
    }
    // 12.2.7: in and out points are already clamped to the extent.
    assert.deepEqual(
      clampInOut(timeline.inPoint, timeline.outPoint, lastFrameOf(graph), metadata.fps),
      { inPoint: timeline.inPoint, outPoint: timeline.outPoint },
      `${name}: in and out points`,
    );
    // 12.8: a marker label is never empty.
    for (const marker of timeline.markers ?? []) assert.notEqual(marker.label, '', `${name}: empty marker label`);
  }
});

test('12.2.2: a command that refuses locked clips leaves every clip on a locked track as it was', () => {
  // The first row of the lock table: these refuse as soon as a clip they would change is locked.
  const checking = ['clip.roll', 'clip.slip', 'clip.slide', 'clip.push', 'clip.join', 'clip.reorder', 'clip.overwrite', 'track.closeGap'];
  let checked = 0;
  for (const entry of part2Cases.filter((candidate) => applied(candidate) && checking.includes(candidate.covers[0]))) {
    const before = fixtures.bases[entry.base].graph;
    const after = entry.expect.graph;
    const locked = new Set(after.timeline.tracks.filter((track) => track.locked).map((track) => track.id));
    for (const item of before.timeline.items.filter((candidate) => locked.has(candidate.trackId))) {
      assert.deepEqual(itemOf(after, item.id), item, `${entry.id}: ${item.id} is on a locked track and changed`);
    }
    checked++;
  }
  assert.ok(checked >= 30, `only ${checked} cases were checked`);
  // And each of them has a case that a lock refuses.
  for (const command of checking) {
    const refused = part2Cases.some(
      (entry) => entry.id.startsWith(`${command}/`) && entry.expect.status === 'rejected' && /locked/.test(entry.expect.detail),
    );
    assert.ok(refused, `${command} has no case refused for a lock`);
  }
});

test('12.2.5: the halves of a split clip have the documented ids, lengths and source frames', () => {
  let checked = 0;
  for (const entry of single('clip.split').filter(applied)) {
    const before = fixtures.bases[entry.base].graph;
    const after = entry.expect.graph;
    const { fps, frameRate } = before.metadata;
    const at = framesOf(entry.envelopes[0].payload.at, frameRate);
    const known = new Set(before.timeline.items.map((item) => item.id));
    for (const original of before.timeline.items) {
      const left = itemOf(after, original.id);
      if (left.durationInFrames === original.durationInFrames) continue;
      const right = after.timeline.items.find(
        (item) => !known.has(item.id) && item.trackId === original.trackId && item.from === at && item.type === original.type,
      );
      assert.ok(right, `${entry.id}: ${original.id} has no right half`);
      assert.equal(left.from, original.from, entry.id);
      assert.equal(left.durationInFrames, at - original.from, entry.id);
      assert.equal(right.durationInFrames, original.from + original.durationInFrames - at, entry.id);
      // Both halves share the lineage: the clip's originId, or its id when it had none.
      assert.equal(left.originId, original.originId ?? original.id, entry.id);
      assert.equal(right.originId, left.originId, entry.id);
      // The right half is appended after every clip the graph already had.
      assert.ok(after.timeline.items.indexOf(right) >= before.timeline.items.length, `${entry.id}: the right half is not appended`);
      if (isMediaClip(original)) {
        const expected = splitSource(original, left.durationInFrames, fps);
        assert.deepEqual({ sourceStart: left.sourceStart, sourceEnd: left.sourceEnd }, expected.left, `${entry.id}: left source`);
        assert.deepEqual({ sourceStart: right.sourceStart, sourceEnd: right.sourceEnd }, expected.right, `${entry.id}: right source`);
      } else {
        // A still's source fields are copied to both halves unchanged.
        for (const half of [left, right]) {
          assert.deepEqual([half.sourceStart, half.sourceEnd], [original.sourceStart, original.sourceEnd], `${entry.id}: still source`);
        }
      }
      checked++;
    }
  }
  assert.ok(checked >= 8, `only ${checked} split clips were checked`);
});

test('12.4.1: a trim without ripple gives the named clip the documented extent and source frames', () => {
  let checked = 0;
  for (const command of ['clip.trimStart', 'clip.trimEnd']) {
    for (const entry of single(command).filter(applied)) {
      const { payload } = entry.envelopes[0];
      if (payload.ripple === true) continue;
      const before = fixtures.bases[entry.base].graph;
      const { fps, frameRate } = before.metadata;
      const original = itemOf(before, payload.clipId);
      const expected =
        command === 'clip.trimStart'
          ? trimStart(original, framesOf(payload.start, frameRate) - original.from, fps)
          : trimEnd(original, framesOf(payload.end, frameRate) - (original.from + original.durationInFrames), fps);
      assert.deepEqual(itemOf(entry.expect.graph, payload.clipId), expected, entry.id);
      checked++;
    }
  }
  assert.ok(checked >= 10, `only ${checked} trims were checked`);
});

