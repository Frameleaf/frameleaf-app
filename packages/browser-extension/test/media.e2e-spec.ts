/**
 * FL-1427: media downloads through the packaged extension. The "Library" and the page are local
 * fixtures and the media is a few generated bytes: no real site, account or sign-in is involved.
 */
const fixtureKey = 'synthetic-capture-key';
const userId = '11111111-1111-4111-8111-111111111111';
const INSPECTION = '0190a000-0000-7000-8000-000000000001';
const ITEM = '0190a000-0000-7000-8000-000000000002';
const ALBUM = '22222222-2222-4222-8222-222222222222';
const body = async (req: IncomingMessage) => {
  const chunks: Buffer[] = [];
  for await (const chunk of req) chunks.push(chunk as Buffer);
  return JSON.parse(Buffer.concat(chunks).toString('utf8') || 'null');
};
async function packaged(temp: string, hosts: string[]) {
  const extensionPath = join(temp, 'extension');
  await cp(resolve(import.meta.dirname, '../dist'), extensionPath, {
    recursive: true,
  });
  const manifest = JSON.parse(
    await readFile(join(extensionPath, 'manifest.json'), 'utf8'),
  );
  // Pregrant only the synthetic hosts; native permission prompts are a separate browser gate.
  manifest.host_permissions = hosts;
  await writeFile(
    join(extensionPath, 'manifest.json'),
    JSON.stringify(manifest),
  );
  return extensionPath;
}
const launch = (
  temp: string,
  extensionPath: string,
  env?: Record<string, string>,
) =>
  chromium.launchPersistentContext(join(temp, 'profile'), {
    channel: 'chromium',
    headless: true,
    ...(env && { env: { ...(process.env as Record<string, string>), ...env } }),
    args: [
      `--disable-extensions-except=${extensionPath}`,
      `--load-extension=${extensionPath}`,
    ],
  });
const extensionOf = async (context: BrowserContext) => {
  const worker =
    context.serviceWorkers()[0] ??
    (await context.waitForEvent('serviceworker'));
  return new URL(worker.url()).hostname;
};

test('downloads a page’s media on the Library, lists what a page plays and keeps the receipt across a browser restart', async () => {
  /** How far the Library's own work has got; it carries on while the browser is closed. */
  let stage: 'inspecting' | 'ready' | 'downloading' | 'saved' = 'inspecting';
  let mediaSupported = true;
  const calls: {
    method: string;
    url: string;
    body?: unknown;
    cookie?: string;
  }[] = [];
  const operation = () => ({
    id: INSPECTION,
    state: stage,
    kind: 'item',
    provider: 'fixture',
    creator: null,
    complete: true,
    limitation: null,
    error: null,
    albumId: stage === 'downloading' || stage === 'saved' ? ALBUM : null,
    subscriptionId: null,
    connectionId: null,
    createdAt: '2026-11-10T00:00:00.000Z',
    updatedAt: '2026-11-10T00:00:00.000Z',
    items: [
      { id: ITEM, title: 'Generated clip', kind: 'video', creator: null },
    ],
    discovered: 1,
    saved: stage === 'saved' ? 1 : 0,
    skipped: 0,
    failed: 0,
  });
  const server = createServer((req, res) => {
    void (async () => {
      const url = req.url ?? '';
      if (url === '/page') {
        res.setHeader('Content-Type', 'text/html');
        res.end(
          '<title>Synthetic video page</title><video src="/media/clip.mp4" muted></video>',
        );
        return;
      }
      if (url.startsWith('/media/')) {
        // generated bytes, not a real recording
        res
          .writeHead(200, { 'Content-Type': 'video/mp4' })
          .end(Buffer.alloc(64));
        return;
      }
      if (url === '/frameleaf/api/server/ping') {
        res.setHeader('Content-Type', 'application/json');
        res.end(JSON.stringify({ res: 'pong' }));
        return;
      }
      if (req.headers['x-api-key'] !== fixtureKey) {
        res.writeHead(401).end();
        return;
      }
      const json = (value: unknown, status = 200) =>
        res
          .writeHead(status, { 'Content-Type': 'application/json' })
          .end(JSON.stringify(value));
      if (url === '/frameleaf/api/capture/capabilities')
        return json({
          version: 1,
          captureSupported: true,
          serverId: 'fixture-server',
          userId,
          maxFileBytes: 104857600,
        });
      if (url === '/frameleaf/api/capture/catalog')
        return json({
          albums: [{ id: ALBUM, albumName: 'Inspiration', parentId: null }],
          tags: [],
        });
      if (!url.startsWith('/frameleaf/api/media-') || !mediaSupported)
        return json({ message: 'Not Found' }, 404);
      calls.push({
        method: req.method ?? 'GET',
        url,
        cookie: req.headers.cookie,
        ...(req.method === 'POST' && { body: await body(req) }),
      });
      if (url === '/frameleaf/api/media-imports/capabilities')
        return json({
          version: 1,
          available: true,
          reason: null,
          ytDlpVersion: null,
          galleryDlVersion: null,
          individualMedia: 'installed-extractors',
          creatorFeeds: 'per-url',
          authentication: ['cookies'],
          qualifiedProviders: [],
        });
      if (url === '/frameleaf/api/media-connections')
        return json({ connections: [] });
      if (url === '/frameleaf/api/media-imports/inspect')
        return json(operation());
      if (url === '/frameleaf/api/media-imports' && req.method === 'POST') {
        stage = 'downloading';
        return json(operation(), 201);
      }
      if (url === `/frameleaf/api/media-imports/${INSPECTION}`)
        return json(operation());
      return json({ message: 'Not Found' }, 404);
    })();
  });
  const temp = await mkdtemp(join(tmpdir(), 'frameleaf-media-'));
  let context: BrowserContext | undefined;
  try {
    await new Promise<void>((done) => server.listen(0, '127.0.0.1', done));
    const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
    const extensionPath = await packaged(temp, ['http://127.0.0.1/*']);
    context = await launch(temp, extensionPath);
    let extensionId = await extensionOf(context);

    const options = await context.newPage();
    await options.goto(`chrome-extension://${extensionId}/options.html`);
    await connectWithKey(options, origin + '/frameleaf', fixtureKey);
    await expect(
      options.getByRole('heading', { name: 'Settings', exact: true }),
    ).toBeVisible();

    const content = await context.newPage();
    await content.goto(origin + '/page');
    await content.waitForLoadState('networkidle');
    await context.addCookies([
      { name: 'site-session', value: 'must-not-leave', url: origin },
    ]);
    let popup = await context.newPage();
    await popup.goto(`chrome-extension://${extensionId}/popup.html`);
    await popup.getByRole('tab', { name: 'Page' }).click();
    await expect(
      popup.getByRole('button', { name: /Download this page/ }),
    ).toBeVisible();
    await expect(
      popup.getByRole('button', { name: 'Save this page', exact: true }),
    ).toBeVisible();

    // Find media: the page's own video is listed, from the page alone
    await content.bringToFront();
    const found = await popup.evaluate(async () =>
      chrome.runtime.sendMessage({ type: 'media-find' }),
    );
    expect(found).toMatchObject({
      ok: true,
      media: {
        found: {
          watching: false,
          items: [{ kind: 'file', name: 'clip.mp4' }],
        },
      },
    });

    // Download this page: the Library is asked about the tab's address, and nothing else is sent
    const inspected = await popup.evaluate(async () =>
      chrome.runtime.sendMessage({ type: 'media-inspect', mode: 'page' }),
    );
    expect(inspected).toMatchObject({
      ok: true,
      media: { operation: { id: INSPECTION, state: 'inspecting' } },
    });
    expect(calls.find((call) => call.url.endsWith('/inspect'))?.body).toEqual({
      urls: [origin + '/page'],
    });
    stage = 'ready';
    const submitted = await popup.evaluate(
      async ([inspectionId, itemId, albumId]) =>
        chrome.runtime.sendMessage({
          type: 'media-download',
          label: 'Synthetic video page',
          inspectionId,
          itemIds: [itemId],
          albumId,
          tagIds: [],
          overrideSuppression: false,
        }),
      [INSPECTION, ITEM, ALBUM],
    );
    expect(submitted).toMatchObject({ ok: true });
    await expect
      .poll(() =>
        calls.find(
          (call) =>
            call.method === 'POST' && call.url.endsWith('/media-imports'),
        ),
      )
      .toBeTruthy();
    const created = calls.find(
      (call) => call.method === 'POST' && call.url.endsWith('/media-imports'),
    )!.body as { idempotencyKey: string; itemIds: string[]; albumId: string };
    expect(created).toMatchObject({
      inspectionId: INSPECTION,
      itemIds: [ITEM],
      albumId: ALBUM,
      overrideSuppression: false,
    });
    expect(created.idempotencyKey).toMatch(/^[\da-f-]{36}$/);
    // the site's own cookies never go to the Library with any of this
    expect(calls.every((call) => !call.cookie)).toBe(true);

    await popup.bringToFront();
    await popup.reload();
    await popup.getByRole('tab', { name: /Saving/ }).click();
    await expect(popup.getByText('Synthetic video page')).toBeVisible();
    await expect(popup.getByText(/Your Library is downloading/)).toBeVisible();

    // The browser closes; the Library finishes on its own; the receipt is still there afterwards.
    await context.close();
    stage = 'saved';
    const before = calls.length;
    context = await launch(temp, extensionPath);
    extensionId = await extensionOf(context);
    popup = await context.newPage();
    await popup.goto(`chrome-extension://${extensionId}/popup.html`);
    await popup.getByRole('tab', { name: /Saving/ }).click();
    await expect(popup.getByText('Synthetic video page')).toBeVisible();
    await expect(popup.getByText(/Saved by your Library/)).toBeVisible({
      timeout: 20000,
    });
    await expect(
      popup.getByRole('link', { name: /Open Synthetic video page/ }),
    ).toHaveAttribute('href', `${origin}/frameleaf/albums/${ALBUM}`);
    // it was read back, never submitted again
    expect(calls.slice(before).some((call) => call.method === 'POST')).toBe(
      false,
    );
    expect(
      await popup.evaluate(async () =>
        JSON.stringify(await chrome.storage.local.get(null)),
      ),
    ).not.toContain('must-not-leave');

    // A Library from before media downloads: media says so, and saving is untouched.
    mediaSupported = false;
    const old = await popup.evaluate(async () =>
      chrome.runtime.sendMessage({ type: 'media-state' }),
    );
    expect(old).toMatchObject({
      ok: false,
      mediaProblem: 'unsupported',
      connection: { status: 'connected' },
    });
    await popup.getByRole('tab', { name: 'Images' }).click();
    await expect(
      popup.getByRole('button', { name: 'Find images on this page' }),
    ).toBeEnabled();
  } finally {
    try {
      await context?.close();
    } finally {
      if (server.listening) {
        const closed = new Promise<void>((done) => server.close(() => done()));
        server.closeAllConnections();
        await closed;
      }
      await rm(temp, { recursive: true, force: true });
    }
  }
});

/**
 * The certificate a Library makes for itself, made here by the Manager's own generator (never a
 * hand-written one). Untrusted, the extension's requests are refused by the browser and nothing in
 * the extension can change that. The second half adds the certificate to a throwaway browser trust
 * store (Linux, where the browser reads one from HOME; no system or personal store is touched) and
 * checks that the same real request then goes through.
 */
test('a Library using the certificate it made for itself is refused until the browser trusts it, and Retry is a real request', async () => {
  const temp = await mkdtemp(join(tmpdir(), 'frameleaf-certificate-'));
  const key = join(temp, 'library.key');
  const cert = join(temp, 'library.crt');
  let openssl = true;
  try {
    execFileSync(
      'openssl',
      selfSignedCertificateArguments('https://localhost', key, cert),
      { stdio: 'ignore' },
    );
  } catch {
    openssl = false;
  }
  test.skip(!openssl, 'openssl is needed to make the Library’s certificate');
  let answered = 0;
  const server = createSecureServer(
    { key: await readFile(key), cert: await readFile(cert) },
    (req, res) => {
      answered++;
      res.setHeader('Content-Type', 'application/json');
      if (req.url === '/api/server/ping')
        res.end(JSON.stringify({ res: 'pong' }));
      else if (req.headers['x-api-key'] !== fixtureKey)
        res.writeHead(401).end();
      else if (req.url === '/api/capture/capabilities')
        res.end(
          JSON.stringify({
            version: 1,
            captureSupported: true,
            serverId: 'fixture-server',
            userId,
            maxFileBytes: 104857600,
          }),
        );
      else if (req.url === '/api/capture/catalog')
        res.end(JSON.stringify({ albums: [], tags: [] }));
      else if (req.url === '/api/media-imports/capabilities')
        res.end(
          JSON.stringify({
            version: 1,
            available: true,
            reason: null,
            authentication: ['cookies'],
          }),
        );
      else res.writeHead(404).end();
    },
  );
  let context: BrowserContext | undefined;
  try {
    await new Promise<void>((done) => server.listen(0, '127.0.0.1', done));
    const origin = `https://localhost:${(server.address() as AddressInfo).port}`;
    const extensionPath = await packaged(temp, ['https://localhost/*']);
    context = await launch(temp, extensionPath);
    let extensionId = await extensionOf(context);
    let options = await context.newPage();
    await options.goto(`chrome-extension://${extensionId}/options.html`);
    await options.getByLabel('Server address').fill(origin);
    await options.getByRole('button', { name: 'Sign in', exact: true }).click();
    // refused by the browser before any request reaches the Library
    await expect(options.getByText('Your server didn’t answer')).toBeVisible();
    await expect(
      options.getByRole('button', { name: /^Open localhost/ }),
    ).toBeVisible();
    await options.getByRole('button', { name: 'Try again' }).click();
    await expect(options.getByText('Your server didn’t answer')).toBeVisible();
    expect(answered).toBe(0);
    await context.close();
    context = undefined;

    let certutil = process.platform === 'linux';
    const home = join(temp, 'home');
    if (certutil)
      try {
        await mkdir(join(home, '.pki', 'nssdb'), { recursive: true });
        const store = `sql:${join(home, '.pki', 'nssdb')}`;
        execFileSync('certutil', ['-d', store, '-N', '--empty-password']);
        execFileSync('certutil', [
          '-d',
          store,
          '-A',
          '-t',
          'C,,',
          '-n',
          'frameleaf-fixture',
          '-i',
          cert,
        ]);
      } catch {
        certutil = false;
      }
    test.skip(
      !certutil,
      'trusting the certificate in a throwaway store is only set up for Linux with certutil',
    );
    context = await launch(temp, extensionPath, { HOME: home });
    extensionId = await extensionOf(context);
    options = await context.newPage();
    await options.goto(`chrome-extension://${extensionId}/options.html`);
    await connectWithKey(options, origin, fixtureKey);
    await expect(
      options.getByRole('heading', { name: 'Settings', exact: true }),
    ).toBeVisible();
    const popup = await context.newPage();
    await popup.goto(`chrome-extension://${extensionId}/popup.html`);
    const before = answered;
    const checked = await popup.evaluate(async () =>
      chrome.runtime.sendMessage({ type: 'media-check' }),
    );
    expect(checked).toMatchObject({ ok: true });
    expect(answered).toBeGreaterThan(before);
  } finally {
    try {
      await context?.close();
    } finally {
      if (server.listening) {
        const closed = new Promise<void>((done) => server.close(() => done()));
        server.closeAllConnections();
        await closed;
      }
      // the private key never outlives the test
      await rm(temp, { recursive: true, force: true });
    }
  }
});
