/** Named icon from the shared map; unknown names fall back to a circle so layouts never break. */
export function Icon({ name, size = 18, className }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      <path
        fill="currentColor"
        d={paths[name] || catalogue[name] || paths.mdiCircleOutline}
      />
    </svg>
  );
}
/** Any Material path imported directly from @mdi/js (for icons outside the shared map). */
export function IconPath({ path, size = 18, className }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      <path fill="currentColor" d={path} />
    </svg>
  );
}
