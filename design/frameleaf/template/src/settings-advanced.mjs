// Source-backed additions to the command-center prototype. Values are illustrative
// drafts, never deployed defaults, observed capabilities, credentials, or API writes.
// Main contracts: server/src/dtos/config.dto.ts and user-preferences.dto.ts.
// Resource-specific sources are named beside their sections below. Array-backed
// fields use one item per line here; production adapters must validate/resolve them.
// Full source mapping: docs/docs/developer/frameleaf-settings-inventory.md.
const field = (id, label, value, type, help, extra = {}) => ({
  id: `advanced${id}`,
  label,
  value,
  type,
  help,
  impact: "New operations",
  ...extra,
});
const toggle = (id, label, value, help) =>
  field(id, label, value, "toggle", help);
const text = (id, label, value, help) => field(id, label, value, "text", help);
const lines = (id, label, value, help) =>
  field(id, label, value, "textarea", help);
const url = (id, label, value, help) => field(id, label, value, "url", help);
const select = (id, label, value, options, help) =>
  field(id, label, value, "select", help, { options });
const number = (id, label, value, unit, min, max, help) =>
  field(id, label, value, "number", help, {
    unit,
    min,
    max,
    integer:
      Number.isInteger(min) &&
      Number.isInteger(max) &&
      !["score", "distance", "GiB", "%", "USD/hour"].includes(unit),
  });
const policy = (id, label, value, help) => ({
  ...field(
    id,
    label,
    value,
    typeof value === "boolean" ? "toggle" : "text",
    help,
  ),
  locked: true,
  policy: "Required behavior",
  impact: "Required behavior",
});
const section = (id, title, description, fields) => ({
  id: `advanced-${id}`,
  title,
  description,
  fields,
});

