import { getAlbumIconCatalogue, type AlbumIconCatalogueResponseDto } from '@frameleaf/sdk';
import { ALBUM_ICONS, DEFAULT_ALBUM_ICON_PATH } from '$lib/utils/album-icons';

/**
 * Icon catalogue access for every Frameleaf icon chooser.
 *
 * What is valid, and which icons are suggested first, comes from the server
 * (`GET /albums/icons`) so no client bundles the catalogue to know it. The SVG
 * geometry for rendering is a display asset like a font: it is fetched as a
 * static JSON asset (generated at build time by vite.config.ts's
 * frameleaf-mdi-icon-paths plugin, from the same `@mdi/js` package) the first
 * time an icon outside the 31 legacy keys has to be drawn, never in the main
 * bundle. FL-139: this used to be `import('@mdi/js')`, a dynamic import of the
 * whole npm module - since the app also statically imports named icons from
 * that same module everywhere, Rollup kept all 7,448 exports in one shared
 * chunk that loaded eagerly on every route. A static asset isn't part of any
 * JS module graph, so it can't be pulled into that chunk.
 *
 * The extra packs (Tabler Icons, Material Symbols, IconOven) work the same way,
 * one static asset per pack (`/icon-packs/<prefix>.json`, generated by
 * web/scripts/icon-packs.mjs), fetched the first time one of its icons is drawn.
 * A stored pack icon is the Iconify id `<prefix>:<name>`.
 */

/**
 * A drawable icon. A plain string is one filled path on the 24 unit grid (every
 * Material Design Icons shape); anything else lists its filled path and its
 * round-capped stroked paths by stroke width. Render with `AlbumIcon`.
 */
export type IconShape = string | { box?: number; fill?: string; strokes?: [width: number, path: string][] };
export type IconPaths = Record<string, IconShape>;

const MDI_PACK = 'mdi';

let cataloguePromise: Promise<AlbumIconCatalogueResponseDto> | undefined;
const pathsPromises = new Map<string, Promise<IconPaths>>();
const loadedPaths = new Map<string, IconPaths>();

export const loadIconCatalogue = (): Promise<AlbumIconCatalogueResponseDto> => {
  cataloguePromise ??= getAlbumIconCatalogue().catch((error: unknown) => {
    cataloguePromise = undefined;
    throw error;
  });
  return cataloguePromise;
};

/** Fetch one pack's geometry once; `pack` comes from {@link iconPackOf}. */
export const loadIconPaths = (pack: string = MDI_PACK): Promise<IconPaths> => {
  let promise = pathsPromises.get(pack);
  if (!promise) {
    promise = fetch(pack === MDI_PACK ? '/mdi-icon-paths.json' : `/icon-packs/${pack}.json`)
      .then(async (response) => {
        if (!response.ok) {
          throw new Error(`Failed to load icon paths (HTTP ${response.status})`);
        }
        const paths = (await response.json()) as IconPaths;
        loadedPaths.set(pack, paths);
        return paths;
      })
      .catch((error: unknown) => {
        pathsPromises.delete(pack);
        throw error;
      });
    pathsPromises.set(pack, promise);
  }
  return promise;
};

/** A pack's geometry when it has already arrived, so an icon can draw at once instead of flashing the default. */
export const loadedIconPaths = (pack: string): IconPaths | undefined => loadedPaths.get(pack);

/** Test seam: forget cached results so the next call fetches again. */
export const resetIconCatalogueCache = () => {
  cataloguePromise = undefined;
  pathsPromises.clear();
  loadedPaths.clear();
};

const MDI_NAME = /^mdi[A-Z][A-Za-z0-9]{1,79}$/;
// Only lower-case letters, digits and hyphens reach the asset URL built from the prefix.
const PACK_NAME = /^([a-z0-9]+(?:-[a-z0-9]+)*):([a-z0-9]+(?:-[a-z0-9]+)*)$/;

/** The pack whose geometry draws a stored icon; undefined for legacy keys and anything not drawable. */
export const iconPackOf = (name: string | null | undefined): string | undefined => {
  if (!name || name.length > 80 || Object.hasOwn(ALBUM_ICONS, name)) {
    return undefined;
  }
  return MDI_NAME.test(name) ? MDI_PACK : PACK_NAME.exec(name)?.[1];
};

/**
 * Resolve a stored icon (a Material Design Icons name, a pack icon or a legacy
 * kebab key) to its shape. Legacy keys resolve without any asset; a name that is
 * not drawable yet (asset still loading, or unknown) falls back to the default.
 * `paths` is the geometry of the icon's own pack ({@link iconPackOf}).
 */
export const iconShapeFor = (name: string | null | undefined, paths?: IconPaths): IconShape => {
  if (!name) {
    return DEFAULT_ALBUM_ICON_PATH;
  }
  if (Object.hasOwn(ALBUM_ICONS, name)) {
    return ALBUM_ICONS[name as keyof typeof ALBUM_ICONS];
  }
  const pack = iconPackOf(name);
  if (!pack || !paths) {
    return DEFAULT_ALBUM_ICON_PATH;
  }
  const key = pack === MDI_PACK ? name : name.slice(pack.length + 1);
  return Object.hasOwn(paths, key) ? paths[key] : DEFAULT_ALBUM_ICON_PATH;
};

export const needsIconPaths = (name: string | null | undefined): boolean => iconPackOf(name) !== undefined;

/** "mdiCameraBurst" -> "camera burst", "tabler:beach-bag" -> "beach bag"; the curated label wins when there is one. */
export const derivedIconLabel = (name: string): string =>
  name.includes(':')
    ? name.slice(name.indexOf(':') + 1).replaceAll('-', ' ')
    : name
        .replace(/^mdi/, '')
        .replaceAll(/([A-Z])/g, ' $1')
        .replaceAll(/(\d+)/g, ' $1')
        .trim()
        .toLowerCase();

